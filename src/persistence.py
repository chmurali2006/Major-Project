"""Atomic artifacts and portable source fingerprints (works without .git)."""
import hashlib
import json
import os
from pathlib import Path
import tempfile


def source_digest(root):
    root = Path(root)
    h = hashlib.sha256()
    for p in sorted([*root.glob('src/*.py'), *root.glob('scripts/*.py')]):
        h.update(p.relative_to(root).as_posix().encode())
        h.update(p.read_bytes())
    return h.hexdigest()


def atomic_write(path, writer):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=path.name + '.', suffix='.tmp')
    try:
        with os.fdopen(fd, 'wb') as fh:
            writer(fh)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def atomic_json(path, value):
    atomic_write(path, lambda f: f.write((json.dumps(value, indent=2, allow_nan=False)+'\n').encode()))


def load_checkpoint(path, device='cpu'):
    import torch
    # Only load checkpoints generated by this project from a trusted location.
    return torch.load(path, map_location=device, weights_only=False)


def seal_artifacts(directory, name, suffixes):
    directory = Path(directory)
    paths = [directory / (name + suffix) for suffix in suffixes]
    atomic_json(directory / f'{name}_artifacts.json',
                {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in paths})


def artifacts_valid(directory, name, suffixes):
    directory = Path(directory)
    seal = directory / f'{name}_artifacts.json'
    try:
        hashes = json.loads(seal.read_text())
        expected = {name + suffix for suffix in suffixes}
        return set(hashes) == expected and all(
            hashlib.sha256((directory / p).read_bytes()).hexdigest() == hashes[p] for p in expected)
    except (OSError, ValueError, KeyError, TypeError):
        return False
